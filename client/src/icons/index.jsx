export function StatusDot({ status, className = 'w-2 h-2' }) {
  const colors = {
    ok: 'text-green-400',
    healthy: 'text-green-400',
    degraded: 'text-yellow-400',
    error: 'text-red-400',
    unknown: 'text-white/30',
  }
  const color = colors[status] || colors.unknown
  return (
    <svg className={`${className} ${color}`} viewBox="0 0 8 8" fill="currentColor">
      <circle cx="4" cy="4" r="4" />
    </svg>
  )
}
